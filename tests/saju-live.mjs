import assert from 'node:assert/strict';
import { SUPABASE_URL as base, SUPABASE_PUBLISHABLE_KEY as key } from '../config.js';
const auth = await fetch(base+'/auth/v1/signup',{method:'POST',headers:{apikey:key,'Content-Type':'application/json'},body:JSON.stringify({data:{}}),signal:AbortSignal.timeout(15000)});
assert.equal(auth.status,200,'anonymous test sign-in');
const session=await auth.json();
assert(session.access_token,'session required');
console.log('::add-mask::'+session.access_token);
if(session.refresh_token) console.log('::add-mask::'+session.refresh_token);
const headers={apikey:key,authorization:'Bearer '+session.access_token,'Content-Type':'application/json',Origin:'https://jjimjiljung.yullul.com'};
const started=Date.now();
const first=await fetch(base+'/functions/v1/saju-ai',{method:'POST',headers,body:JSON.stringify({pillar:'갑자 / 무오'}),signal:AbortSignal.timeout(18000)});
const data=await first.json();
console.log(JSON.stringify({stage:'generation',status:first.status,elapsed_ms:Date.now()-started,code:data.code||data.error,chars:data.text?.length,korean:/[가-힣]/.test(data.text||'')}));
assert.equal(first.status,200);
assert.match(data.text,/[가-힣]/);
const again=await fetch(base+'/functions/v1/saju-ai',{method:'POST',headers,body:JSON.stringify({pillar:'갑자 / 무오'}),signal:AbortSignal.timeout(15000)});
const cached=await again.json();
assert.equal(cached.cached,true);
assert.equal(cached.text,data.text);
const rows=await fetch(base+'/rest/v1/daily_fortunes?select=fortune_text&user_id=eq.'+session.user.id,{headers});
assert.equal(rows.status,200);
const saved=await rows.json();
assert(saved.some(row=>row.fortune_text===data.text),'AI text must be saved');
console.log('PASS: Korean AI text generated, persisted, and returned from daily cache.');
